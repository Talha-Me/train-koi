// Helper: Get train profile by ID or by Bangla train name
export const getTrainProfile = (train) => {
  if (!train) return null;
  // 1. Check direct ID match
  if (train.id && trainProfiles[train.id]) {
    return trainProfiles[train.id];
  }
  // 2. Check if name matches any profile
  const rawName = (train.name || "").toLowerCase();
  for (const id in trainProfiles) {
    const profile = trainProfiles[id];
    if (rawName.includes(profile.banglaName.toLowerCase())) {
      return profile;
    }
  }
  return null;
};

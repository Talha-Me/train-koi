async function seedBatch3() {
  console.log('--- Connecting to MongoDB Atlas ---');
  await mongoose.connect(process.env.MONGO_URI);
  console.log('✅ Connected successfully!');

  console.log('\n--- Validating Word Counts ---');
  let hasError = false;

  blogsData.forEach((b, idx) => {
    const wc = countWords(b.content);
    console.log(`Blog ${idx + 1}: "${b.title.substring(0, 35)}..." -> ${wc} words`);
    if (wc < 800) {
      console.error(`❌ Blog ${idx + 1} has LESS THAN 800 WORDS (${wc})!`);
      hasError = true;
    }
  });

  newsData.forEach((n, idx) => {
    const wc = countWords(n.content);
    console.log(`News ${idx + 1}: "${n.title.substring(0, 35)}..." -> ${wc} words`);
    if (wc < 800) {
      console.error(`❌ News ${idx + 1} has LESS THAN 800 WORDS (${wc})!`);
      hasError = true;
    }
  });

  if (hasError) {
    console.error('Validation failed. Aborting database insertion.');
    await mongoose.disconnect();
    process.exit(1);
  }

  console.log('✅ All 10 articles passed the 800+ words criteria!\n');

  console.log('--- Inserting / Updating Blogs ---');
  for (const b of blogsData) {
    const res = await Blog.findOneAndUpdate(
      { slug: b.slug },
      { $set: b },
      { upsert: true, new: true }
    );
    console.log(`Saved Blog: [${res.slug}] (ID: ${res._id})`);
  }

  console.log('\n--- Inserting / Updating News ---');
  for (const n of newsData) {
    const res = await News.findOneAndUpdate(
      { slug: n.slug },
      { $set: n },
      { upsert: true, new: true }
    );
    console.log(`Saved News: [${res.slug}] (ID: ${res._id})`);
  }

  const totalBlogs = await Blog.countDocuments();
  const totalNews = await News.countDocuments();
  console.log(`\n🎉 BATCH 3 COMPLETED!`);
  console.log(`Total Blogs in Database: ${totalBlogs}`);
  console.log(`Total News in Database: ${totalNews}`);
  console.log(`Grand Total Content: ${totalBlogs + totalNews}`);

  await mongoose.disconnect();
  console.log('Disconnected from MongoDB.');
}

seedBatch3().catch(err => {
  console.error('Fatal error in seedBatch3:', err);
  process.exit(1);
});

async function runSeed() {
  await mongoose.connect(process.env.MONGO_URI);
  console.log('\n✅ Connected to MongoDB Atlas.');

  console.log('\n--- Seeding 5 SEO Blogs (800+ words) ---');
  for (const b of blogsData) {
    await Blog.findOneAndUpdate({ slug: b.slug }, b, { upsert: true, returnDocument: 'after' });
    console.log(`Upserted Blog: "${b.title.substring(0, 35)}..." (${countWords(b.content)} words)`);
  }

  console.log('\n--- Seeding 5 SEO News (800+ words) ---');
  for (const n of newsData) {
    await News.findOneAndUpdate({ slug: n.slug }, n, { upsert: true, returnDocument: 'after' });
    console.log(`Upserted News: "${n.title.substring(0, 35)}..." (${countWords(n.content)} words)`);
  }

  const totalB = await Blog.countDocuments();
  const totalN = await News.countDocuments();
  console.log(`\n🎉 SEEDING COMPLETE! Total Blogs: ${totalB}, Total News: ${totalN}`);
  await mongoose.disconnect();
}

runSeed().catch(console.error);

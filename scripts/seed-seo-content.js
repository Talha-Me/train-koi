async function seed() {
  try {
    const mongoUri = process.env.MONGO_URI;
    if (!mongoUri) {
      throw new Error('MONGO_URI is missing from backend/.env');
    }

    console.log('Connecting to MongoDB Atlas...');
    await mongoose.connect(mongoUri);
    console.log('✅ Connected to MongoDB Atlas successfully.');

    // 1. Seed Blogs
    console.log('\n--- Seeding 5 SEO Blogs ---');
    for (const b of seoBlogs) {
      const existing = await Blog.findOne({ slug: b.slug });
      if (existing) {
        await Blog.updateOne({ slug: b.slug }, { $set: b });
        console.log(`Updated Blog: "${b.title}"`);
      } else {
        await Blog.create(b);
        console.log(`Created Blog: "${b.title}"`);
      }
    }

    // 2. Seed News
    console.log('\n--- Seeding 5 SEO News ---');
    for (const n of seoNews) {
      const existing = await News.findOne({ slug: n.slug });
      if (existing) {
        await News.updateOne({ slug: n.slug }, { $set: n });
        console.log(`Updated News: "${n.title}"`);
      } else {
        await News.create(n);
        console.log(`Created News: "${n.title}"`);
      }
    }

    const totalBlogs = await Blog.countDocuments();
    const totalNews = await News.countDocuments();
    console.log(`\n🎉 Success! Total Blogs in DB: ${totalBlogs}, Total News in DB: ${totalNews}`);

    await mongoose.disconnect();
    console.log('Database connection closed.');
  } catch (err) {
    console.error('❌ Seeding error:', err.message);
    process.exit(1);
  }
}

seed();
